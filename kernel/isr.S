isr_common:
    pusha
    movw %ds, %ax
    pushl %eax
    movw $0x10, %ax
    movw %ax, %ds
    movw %ax, %es
    movw %ax, %fs
    movw %ax, %gs

    pushl %esp
    call int_dispatch
    addl $4, %esp

    popl %eax
    movw %ax, %ds
    movw %ax, %es
    movw %ax, %fs
    movw %ax, %gs
    popa
    addl $8, %esp        /* drop int_no + err_code */
    iret

/* load IDT: void idt_flush(u32 ptr) */
    .global idt_flush
idt_flush:
    movl 4(%esp), %eax
    lidt (%eax)
    ret
