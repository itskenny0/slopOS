/* CPU exception + IRQ stubs. Each pushes a uniform frame and calls the
 * common C dispatcher. */
    .code32
    .section .text

.macro ISR_NOERR n
    .global isr\n
isr\n:
    cli
    pushl $0
    pushl $\n
    jmp isr_common
.endm

.macro ISR_ERR n
    .global isr\n
isr\n:
    cli
    pushl $\n
    jmp isr_common
.endm

.macro IRQ n, vec
    .global irq\n
irq\n:
    cli
    pushl $0
    pushl $\vec
    jmp isr_common
.endm

